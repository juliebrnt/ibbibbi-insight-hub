def to_html(b: dict) -> str:
    e = html.escape
    parts = [f"<!doctype html><html lang='en-GB'><head><meta charset='utf-8'><title>{e(b['title'])}</title><style>{CSS}</style></head><body><div class='wrap'>",
             f"<h1>{e(b['title'])}</h1><div class='muted'>{e(b['period'])} ({b['start']} to {b['end']})"
             + (" <span class='demo'>Demo data, not real customers</span>" if b["demo"] else "") + "</div>", "<h2>Key numbers</h2><div class='kpis'>"]
    for k in b["kpis"]:
        ch = f"<span class='muted'>{k['change']:+.0f}% vs previous</span>" if k["change"] is not None else ""
        parts.append(f"<div class='kpi'><span class='muted'>{e(k['label'])}</span><b>{e(k['value'])}</b>{ch}</div>")
    parts.append("</div><h2>Top insights</h2>")
    for i, ins in enumerate(b["insights"], 1):
        parts.append(f"<div class='card'><h3>{i}. {e(ins['title'])}</h3><div>{e(ins['finding'])}</div>"
                     f"<div class='muted' style='margin-top:6px'>{e(ins['why_it_matters'])}</div>"
                     f"<div class='do'><b>Do this:</b> {e(ins['recommended_action'])}</div>"
                     f"<div class='muted' style='margin-top:6px'>Effort {e(ins['effort'])} · Confidence {ins['confidence'] * 100:.0f}% · {e(ins['linked_goal'])}"
                     + (" · Wording by AI, numbers checked" if ins.get("ai_written") else "") + "</div></div>")
    if b["changed"]:
        parts.append("<h2>What changed</h2><ul>" + "".join(
            f"<li>{e(c['label'])}: {e(c['prev_display'])} to <b>{e(c['display'])}</b> ({c['change']:+.0f}%)</li>" for c in b["changed"]) + "</ul>")
    if b["goals"]:
        parts.append("<h2>Goals</h2>")
        for g in b["goals"]:
            pct = (g["progress"] or 0) * 100
            parts.append(f"<div class='card'><b>{e(g['title'])}</b><div class='muted'>Now {e(g['current_display'])} · target {e(g['target_display'])}</div>"
                         f"<div class='bar'><i style='width:{pct:.0f}%'></i></div></div>")
    if b["due"]:
        parts.append("<h2>Decisions to review</h2><ul>" + "".join(f"<li>{e(d['title'])} (review {str(d['review_date'])[:10]})</li>" for d in b["due"]) + "</ul>")
    if b["learnings"]:
        parts.append("<h2>Recent learnings</h2><ul>" + "".join(f"<li><b>{e(d['title'])}:</b> {e(d['learning'])}</li>" for d in b["learnings"]) + "</ul>")
    parts.append("<p class='muted' style='margin-top:28px'>Every number comes from your uploaded data. Generated by iBBIBBI Insight Hub.</p></div></body></html>")
    return "".join(parts)


