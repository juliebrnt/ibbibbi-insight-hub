"""Weekly briefing: one page for the founders, as data, HTML and Markdown."""
from __future__ import annotations

import html
from datetime import datetime

from ..analytics import common, feedback, metrics, sales, social
from . import plan, rules


def build(ws: str, rng: str = "28d") -> dict:
    p = common.period(ws, rng)
    ctx = rules.context(ws, p)
    ins = rules.run(ws, p, ctx)["insights"]
    s, f, so = ctx["sales"], ctx["feedback"], ctx["social"]
    kpis = []
    if not s.get("empty"):
        kpis += [("Revenue", common.eur(s["kpis"]["revenue"]["value"]), s["kpis"]["revenue"]["change"]),
                 ("Orders", f"{s['kpis']['orders']['value']:,}", s["kpis"]["orders"]["change"])]
    if not f.get("empty"):
        r = f["kpis"]["rating"]["value"]
        kpis.append(("Average rating", f"{r:.1f} / 5" if r else "n/a", None))
        if f["kpis"]["nps"]["value"] is not None:
            kpis.append(("NPS (12 months)", str(f["kpis"]["nps"]["value"]), None))
    if not so.get("empty"):
        kpis.append(("Posting consistency", f"{so['kpis']['consistency']['value']} / 100", None))
    decisions = plan.list_decisions(ws)
    return {
        "title": f"Weekly briefing · {p.end:%-d %B %Y}", "period": p.label, "start": p.start.isoformat(), "end": p.end.isoformat(),
        "kpis": [{"label": a, "value": b, "change": c} for a, b, c in kpis],
        "insights": ins[:3], "actions": [i["recommended_action"] for i in ins[:3]],
        "changed": rules.what_changed(ws, p),
        "goals": plan.list_goals(ws),
        "due": [d for d in decisions if d.get("due")],
        "learnings": [d for d in decisions if d.get("learning")][:3],
        "generated": datetime.now().isoformat(timespec="minutes"), "demo": ws == "demo",
    }


def to_markdown(b: dict) -> str:
    out = [f"# {b['title']}", f"_{b['period']} ({b['start']} to {b['end']})_" + (" · Demo data, not real customers" if b["demo"] else ""), "",
           "## Key numbers"]
    for k in b["kpis"]:
        ch = f" ({k['change']:+.0f}% vs previous period)" if k["change"] is not None else ""
        out.append(f"- **{k['label']}:** {k['value']}{ch}")
    out += ["", "## Top insights"]
    for i, ins in enumerate(b["insights"], 1):
        out += [f"### {i}. {ins['title']}", ins["finding"], "", f"**Why it matters:** {ins['why_it_matters']}",
                f"**Do this:** {ins['recommended_action']}", f"_Effort: {ins['effort']} · Confidence: {ins['confidence'] * 100:.0f}% · Goal: {ins['linked_goal']}_", ""]
    if b["changed"]:
        out += ["## What changed"] + [f"- {c['label']}: {c['prev_display']} to {c['display']} ({c['change']:+.0f}%)" for c in b["changed"]] + [""]
    if b["goals"]:
        out += ["## Goals"] + [f"- {g['title']}: now {g['current_display']}, target {g['target_display']}" +
                               (f" ({g['progress'] * 100:.0f}% of the way)" if g["progress"] is not None else "") for g in b["goals"]] + [""]
    if b["due"]:
        out += ["## Decisions to review"] + [f"- {d['title']} (review date {str(d['review_date'])[:10]})" for d in b["due"]] + [""]
    if b["learnings"]:
        out += ["## Recent learnings"] + [f"- **{d['title']}:** {d['learning']}" for d in b["learnings"]] + [""]
    out.append("_Every number comes from your uploaded data. Generated by iBBIBBI Insight Hub._")
    return "\n".join(out)


